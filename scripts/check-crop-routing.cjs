// Runs in Linux/n8n, with all filesystem effects confined to a unique test directory.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const directory = fs.mkdtempSync(path.join(root, 'temp/crop-check-'));
const local = name => { assert.ok(name.startsWith('/files/')); return path.join(directory, name.slice(7)); };
const fakeFs = {};
for (const method of ['readFileSync', 'writeFileSync', 'openSync', 'unlinkSync', 'statSync', 'existsSync']) fakeFs[method] = (name, ...args) => fs[method](local(name), ...args);
fakeFs.renameSync = (from, to) => fs.renameSync(local(from), local(to)); fakeFs.closeSync = fd => fs.closeSync(fd);
const config = { allowedUserIds: [456, 789], allowedChatIds: [456, 789], services: ['facebook'], queue: { enabled: true } };
const code = ['telegram-queue-store', 'telegram-image-crop-intake', 'telegram-album-intake'].map(name => fs.readFileSync(path.join(root, 'workflows/code/' + name + '.js'), 'utf8')).join('\n');
const run = message => JSON.parse(JSON.stringify(vm.runInNewContext('(()=>{const publisherConfig=' + JSON.stringify(config) + ';\n' + code + '\n})()', { require: name => name === 'fs' ? fakeFs : crypto, $input: { first: () => ({ json: { message } }) } })));
let id = 1;
const message = (extra, owner = 456) => ({ message_id: id++, chat: { id: owner, type: 'private' }, from: { id: owner }, ...extra });
const imageFile = extra => message({ document: { file_id: 'original', file_size: 1000, mime_type: 'image/png', file_name: 'original.png' }, ...extra });
assert.equal(run(message({ text: '/crop' }))[0].json.shouldPublish, false);
assert.match(run(message({ photo: [{ file_id: 'compressed', width: 92, height: 1280 }] }))[0].json.text, /File\/Tài liệu/);
const image = imageFile({});
const cropped = run(image)[0].json;
assert.equal(cropped.isCropRequest, true); assert.equal(cropped.shouldPublish, false);
assert.equal(cropped.cropOutput, 'collage');
assert.deepEqual(run(image), [], 'Redelivery cannot produce duplicate crop');
assert.equal(run(imageFile({ caption: 'This is not a publishing request' }))[0].json.shouldPublish, false);
assert.equal(run(message({ document: { file_id: 'document', mime_type: 'image/png', file_size: 2000 } }))[0].json.isCropRequest, true);
assert.match(run(message({ video: { file_id: 'video' } }))[0].json.text, /cắt ảnh/);
assert.match(run(imageFile({ media_group_id: 'album' }))[0].json.text, /từng ảnh riêng/);
assert.deepEqual(run(imageFile({ media_group_id: 'album' })), []);
assert.match(run(message({ document: { file_id: 'large', mime_type: 'image/jpeg', file_size: 21 * 1024 * 1024 } }))[0].json.text, /20 MB/);
assert.equal(run(message({ photo: [{ file_id: 'other' }], caption: 'Other user post' }, 789))[0].json.shouldPublish, true, 'Mode is isolated by chat and user');
assert.deepEqual(run(message({ text: '/crop' }, 111)), []);
assert.equal(JSON.parse(fakeFs.readFileSync('/files/telegram-content-queue.json', 'utf8')).posts.length, 0);
run(message({ text: '/done' }));
assert.equal(run(imageFile({ caption: 'Normal publishing after exit' }))[0].json.shouldPublish, true);
assert.equal(run(imageFile({ caption: '/crop parts' }))[0].json.cropOutput, 'parts', 'Caption /crop parts selects native parts');
assert.equal(run(imageFile({}))[0].json.cropOutput, 'parts', 'Output selection persists');
assert.equal(run(imageFile({ caption: '/crop png' }))[0].json.cropOutput, 'png');
assert.equal(run(imageFile({}))[0].json.cropOutput, 'png');
assert.equal(run(imageFile({ file_name: 'unused', caption: '/crop' }))[0].json.cropOutput, 'collage');
console.log('PASS crop routing: reject compressed photos, original document and native-parts modes, no publishing, per-user isolation, redelivery/album dedup, size guard and /done.');
